import { existsSync, readFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';

import { errorMessage } from '../utils/error-formatter.js';

const OLD_APP_NAME = 'Navidrome Player';
const OLD_RUNNER_TEXT_MARKER = 'Generated by make-launcher';
const OLD_BUNDLE_ID = 'com.navidrome.mcp.webplayer';
const OLD_DESKTOP_ENTRY_MARKER = `Name=${OLD_APP_NAME}`;
const OLD_ICON_FILE = 'navidrome-player.ico';
const OLD_DESKTOP_ENTRY_FILE = 'navidrome-player.desktop';

export interface OldShortcutContext {
  platform: NodeJS.Platform;
  desktopDir: string;
  homeDir: string;
  /** Null when APPDATA is unset, so the Start Menu holds no old file to find. */
  startMenuDir: string | null;
  runnerDir: string;
  /** The renamed icon asset, which the old generator's icon copy must equal. */
  iconIcoPath: string;
}

export interface OldShortcutReport {
  removed: string[];
  kept: { path: string; reason: string }[];
}

interface OldCandidate {
  path: string;
  /** True only when the file at the path holds proof that the old generator wrote it. */
  wroteByOldGenerator: () => boolean;
}

function readBytes(path: string): Buffer | null {
  try {
    return readFileSync(path);
  } catch {
    return null;
  }
}

function fileHolds(path: string, needle: string | Buffer): boolean {
  return readBytes(path)?.includes(needle) ?? false;
}

function fileEquals(path: string, otherPath: string): boolean {
  const bytes = readBytes(path);
  const other = readBytes(otherPath);
  return bytes !== null && other !== null && bytes.equals(other);
}

function windowsCandidates(ctx: OldShortcutContext): OldCandidate[] {
  // The old .lnk's argument is the old runner path, and WScript.Shell stores it as UTF-16LE.
  const oldRunnerPath = Buffer.from(join(ctx.runnerDir, `${OLD_APP_NAME}.vbs`), 'utf16le');
  const shortcutDirs = ctx.startMenuDir === null ? [ctx.desktopDir] : [ctx.desktopDir, ctx.startMenuDir];
  const candidates: OldCandidate[] = [];

  for (const dir of shortcutDirs) {
    const lnkPath = join(dir, `${OLD_APP_NAME}.lnk`);
    candidates.push({ path: lnkPath, wroteByOldGenerator: () => fileHolds(lnkPath, oldRunnerPath) });
  }
  for (const dir of [...shortcutDirs, ctx.runnerDir]) {
    const vbsPath = join(dir, `${OLD_APP_NAME}.vbs`);
    candidates.push({ path: vbsPath, wroteByOldGenerator: () => fileHolds(vbsPath, OLD_RUNNER_TEXT_MARKER) });
  }
  const iconPath = join(ctx.runnerDir, OLD_ICON_FILE);
  candidates.push({ path: iconPath, wroteByOldGenerator: () => fileEquals(iconPath, ctx.iconIcoPath) });
  return candidates;
}

function macCandidates(ctx: OldShortcutContext): OldCandidate[] {
  const appPath = join(ctx.desktopDir, `${OLD_APP_NAME}.app`);
  return [{ path: appPath, wroteByOldGenerator: () => fileHolds(join(appPath, 'Contents', 'Info.plist'), OLD_BUNDLE_ID) }];
}

function linuxCandidates(ctx: OldShortcutContext): OldCandidate[] {
  const dirs = [join(ctx.homeDir, '.local', 'share', 'applications'), ctx.desktopDir];
  return dirs.map((dir) => {
    const entryPath = join(dir, OLD_DESKTOP_ENTRY_FILE);
    return { path: entryPath, wroteByOldGenerator: () => fileHolds(entryPath, OLD_DESKTOP_ENTRY_MARKER) };
  });
}

const CANDIDATES_BY_PLATFORM: Partial<Record<NodeJS.Platform, (ctx: OldShortcutContext) => OldCandidate[]>> = {
  win32: windowsCandidates,
  darwin: macCandidates,
  linux: linuxCandidates,
};

function candidatesFor(ctx: OldShortcutContext): OldCandidate[] {
  return CANDIDATES_BY_PLATFORM[ctx.platform]?.(ctx) ?? [];
}

/**
 * Touches only the old generator's own paths, and only a file whose content proves the old
 * generator wrote it. A user file that shares a name stays and is reported.
 */
export function removeOldShortcuts(ctx: OldShortcutContext): OldShortcutReport {
  const report: OldShortcutReport = { removed: [], kept: [] };
  const seen = new Set<string>();

  for (const candidate of candidatesFor(ctx)) {
    if (seen.has(candidate.path) || !existsSync(candidate.path)) continue;
    seen.add(candidate.path);

    if (!candidate.wroteByOldGenerator()) {
      report.kept.push({ path: candidate.path, reason: 'not written by the old generator' });
      continue;
    }
    try {
      rmSync(candidate.path, { recursive: true });
      report.removed.push(candidate.path);
    } catch (err) {
      report.kept.push({ path: candidate.path, reason: `could not remove it: ${errorMessage(err)}` });
    }
  }
  return report;
}
