import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { removeOldShortcuts, type OldShortcutContext } from '../../../src/shortcut/old-cleanup.js';

const OLD_ICON_BYTES = Buffer.from([1, 2, 3, 4]);

let root = '';
let ctx: OldShortcutContext;

function put(path: string, content: string | Buffer): string {
  mkdirSync(join(path, '..'), { recursive: true });
  writeFileSync(path, content);
  return path;
}

function contextFor(platform: NodeJS.Platform): OldShortcutContext {
  return {
    platform,
    desktopDir: join(root, 'Desktop'),
    homeDir: join(root, 'home'),
    startMenuDir: join(root, 'StartMenu'),
    runnerDir: join(root, 'runner'),
    iconIcoPath: put(join(root, 'assets', 'jukebox-remote.ico'), OLD_ICON_BYTES),
  };
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'ndmcp-old-shortcuts-'));
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe('old Windows shortcut files', () => {
  beforeEach(() => {
    ctx = contextFor('win32');
  });

  it('removes a .lnk that holds the old runner path in UTF-16LE', () => {
    const oldRunner = join(ctx.runnerDir, 'Navidrome Player.vbs');
    const desktopLnk = put(join(ctx.desktopDir, 'Navidrome Player.lnk'), Buffer.concat([Buffer.from('head'), Buffer.from(oldRunner, 'utf16le')]));
    const menuLnk = put(join(ctx.startMenuDir ?? '', 'Navidrome Player.lnk'), Buffer.from(oldRunner, 'utf16le'));

    const report = removeOldShortcuts(ctx);

    expect(report.removed).toEqual([desktopLnk, menuLnk]);
    expect(report.kept).toEqual([]);
    expect(existsSync(desktopLnk)).toBe(false);
    expect(existsSync(menuLnk)).toBe(false);
  });

  it('keeps a .lnk that does not hold the old runner path, and names it', () => {
    const userLnk = put(join(ctx.desktopDir, 'Navidrome Player.lnk'), Buffer.from('a user shortcut', 'utf16le'));
    const asciiLnk = put(join(ctx.startMenuDir ?? '', 'Navidrome Player.lnk'), join(ctx.runnerDir, 'Navidrome Player.vbs'));

    const report = removeOldShortcuts(ctx);

    expect(report.removed).toEqual([]);
    expect(report.kept.map((entry) => entry.path)).toEqual([userLnk, asciiLnk]);
    expect(existsSync(userLnk)).toBe(true);
    expect(existsSync(asciiLnk)).toBe(true);
  });

  it('removes a .vbs that says the old generator wrote it, in every old folder', () => {
    const paths = [ctx.desktopDir, ctx.startMenuDir ?? '', ctx.runnerDir].map((dir) =>
      put(join(dir, 'Navidrome Player.vbs'), "' Generated by make-launcher; re-run the generator\r\n"),
    );

    const report = removeOldShortcuts(ctx);

    expect(report.removed).toEqual(paths);
    for (const path of paths) expect(existsSync(path)).toBe(false);
  });

  it('keeps a .vbs without the old generator text', () => {
    const userVbs = put(join(ctx.runnerDir, 'Navidrome Player.vbs'), "' my own script\r\n");

    const report = removeOldShortcuts(ctx);

    expect(report.removed).toEqual([]);
    expect(report.kept).toEqual([{ path: userVbs, reason: 'not written by the old generator' }]);
    expect(existsSync(userVbs)).toBe(true);
  });

  it('removes the old icon copy only when its bytes equal the renamed asset', () => {
    const oldIcon = put(join(ctx.runnerDir, 'navidrome-player.ico'), OLD_ICON_BYTES);

    const matching = removeOldShortcuts(ctx);

    expect(matching.removed).toEqual([oldIcon]);
    expect(existsSync(oldIcon)).toBe(false);

    put(oldIcon, Buffer.from([9, 9, 9]));

    const differing = removeOldShortcuts(ctx);

    expect(differing.removed).toEqual([]);
    expect(differing.kept.map((entry) => entry.path)).toEqual([oldIcon]);
    expect(existsSync(oldIcon)).toBe(true);
  });

  it('keeps an old icon file when the renamed asset is unreadable', () => {
    const oldIcon = put(join(ctx.runnerDir, 'navidrome-player.ico'), OLD_ICON_BYTES);

    const report = removeOldShortcuts({ ...ctx, iconIcoPath: join(root, 'assets', 'missing.ico') });

    expect(report.removed).toEqual([]);
    expect(existsSync(oldIcon)).toBe(true);
  });

  it('skips the Start Menu when no folder is known and reports nothing for absent files', () => {
    const report = removeOldShortcuts({ ...ctx, startMenuDir: null });

    expect(report).toEqual({ removed: [], kept: [] });
  });

  it('touches the new Jukebox Remote files never', () => {
    const newLnk = put(join(ctx.desktopDir, 'Jukebox Remote.lnk'), Buffer.from('new', 'utf16le'));
    const newVbs = put(join(ctx.runnerDir, 'Jukebox Remote.vbs'), "' Generated by make-launcher\r\n");

    const report = removeOldShortcuts(ctx);

    expect(report).toEqual({ removed: [], kept: [] });
    expect(existsSync(newLnk)).toBe(true);
    expect(existsSync(newVbs)).toBe(true);
  });
});

describe('old macOS shortcut bundle', () => {
  beforeEach(() => {
    ctx = contextFor('darwin');
  });

  it('removes the .app whose Info.plist holds the old bundle id', () => {
    const appPath = join(ctx.desktopDir, 'Navidrome Player.app');
    put(join(appPath, 'Contents', 'Info.plist'), '<string>com.navidrome.mcp.webplayer</string>');
    put(join(appPath, 'Contents', 'MacOS', 'launcher'), '#!/bin/bash');

    const report = removeOldShortcuts(ctx);

    expect(report.removed).toEqual([appPath]);
    expect(existsSync(appPath)).toBe(false);
  });

  it('keeps an .app with another bundle id or no Info.plist', () => {
    const otherApp = join(ctx.desktopDir, 'Navidrome Player.app');
    put(join(otherApp, 'Contents', 'Info.plist'), '<string>com.example.other</string>');

    const report = removeOldShortcuts(ctx);

    expect(report.removed).toEqual([]);
    expect(report.kept.map((entry) => entry.path)).toEqual([otherApp]);
    expect(existsSync(otherApp)).toBe(true);

    rmSync(join(otherApp, 'Contents', 'Info.plist'));

    expect(removeOldShortcuts(ctx).kept.map((entry) => entry.path)).toEqual([otherApp]);
  });
});

describe('old Linux desktop entries', () => {
  beforeEach(() => {
    ctx = contextFor('linux');
  });

  it('removes an entry named Navidrome Player in the applications folder and on the Desktop', () => {
    const entry = '[Desktop Entry]\nName=Navidrome Player\n';
    const appsEntry = put(join(ctx.homeDir, '.local', 'share', 'applications', 'navidrome-player.desktop'), entry);
    const deskEntry = put(join(ctx.desktopDir, 'navidrome-player.desktop'), entry);

    const report = removeOldShortcuts(ctx);

    expect(report.removed).toEqual([appsEntry, deskEntry]);
    expect(existsSync(appsEntry)).toBe(false);
    expect(existsSync(deskEntry)).toBe(false);
  });

  it('keeps an entry with another name', () => {
    const deskEntry = put(join(ctx.desktopDir, 'navidrome-player.desktop'), '[Desktop Entry]\nName=Mine\n');

    const report = removeOldShortcuts(ctx);

    expect(report.removed).toEqual([]);
    expect(report.kept).toEqual([{ path: deskEntry, reason: 'not written by the old generator' }]);
    expect(existsSync(deskEntry)).toBe(true);
  });

  it('removes one entry once when the Desktop is the applications folder', () => {
    const appsDir = join(ctx.homeDir, '.local', 'share', 'applications');
    const entry = put(join(appsDir, 'navidrome-player.desktop'), 'Name=Navidrome Player\n');

    const report = removeOldShortcuts({ ...ctx, desktopDir: appsDir });

    expect(report.removed).toEqual([entry]);
    expect(report.kept).toEqual([]);
  });
});

describe('unsupported platform', () => {
  it('removes nothing', () => {
    ctx = contextFor('freebsd');
    const stray = put(join(ctx.desktopDir, 'navidrome-player.desktop'), 'Name=Navidrome Player\n');

    expect(removeOldShortcuts(ctx)).toEqual({ removed: [], kept: [] });
    expect(existsSync(stray)).toBe(true);
  });
});
